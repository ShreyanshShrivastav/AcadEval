import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { AuthProvider } from "@/lib/auth-context";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
  display: "swap",
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
  display: "swap",
});

export const metadata: Metadata = {
  title: {
    template: "%s | AcadEval",
    default: "AcadEval — Academic Project Management & Evaluation",
  },
  description:
    "A unified platform for managing academic projects, teams, submissions, and faculty evaluations.",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full`}
    >
      <body className="h-full antialiased">
        {/* AuthProvider must wrap the entire tree so any page can call useAuth() */}
        <AuthProvider>{children}</AuthProvider>
      </body>
    </html>
  );
}
